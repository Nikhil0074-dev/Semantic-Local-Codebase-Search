import os

import pytest

from slcs.config import Settings
from slcs.scanner import check_content_policy, detect_language, is_sensitive, scan_repository


def scan(root, **kw):
    s = Settings()
    for k, v in kw.items():
        setattr(s, k, v)
    return scan_repository(root, s)


def test_finds_supported_files_and_languages(repo_copy):
    r = scan(repo_copy)
    langs = {f.language for f in r.files}
    assert {"python", "typescript", "go", "java", "sql", "config", "rust"} <= langs
    assert all("/" not in f.rel_path or not f.rel_path.startswith("/") for f in r.files)


def test_excludes_dependency_and_build_dirs(repo_copy):
    paths = {f.rel_path for f in scan(repo_copy).files}
    assert not any(p.startswith(("node_modules/", "dist/")) for p in paths)


def test_sensitive_files_are_skipped_and_reported(repo_copy):
    r = scan(repo_copy)
    assert ".env" not in {f.rel_path for f in r.files}
    assert (".env", "sensitive") in [(s.rel_path, s.reason) for s in r.skipped]


def test_sensitive_templates_allowed():
    assert is_sensitive(".env") and is_sensitive("server.pem") and is_sensitive("id_rsa")
    assert not is_sensitive(".env.example") and not is_sensitive("main.py")


def test_gitignore_respected_and_can_be_disabled(repo_copy):
    on = {f.rel_path for f in scan(repo_copy).files}
    off = {f.rel_path for f in scan(repo_copy, respect_gitignore=False).files}
    assert "scratch/ignored.py" not in on
    assert "scratch/ignored.py" in off


def test_nested_gitignore(tmp_path):
    (tmp_path / "pkg").mkdir()
    (tmp_path / "pkg" / ".gitignore").write_text("secret_gen.py\n")
    (tmp_path / "pkg" / "secret_gen.py").write_text("x = 1\n")
    (tmp_path / "pkg" / "keep.py").write_text("x = 1\n")
    (tmp_path / "secret_gen.py").write_text("x = 1\n")
    paths = {f.rel_path for f in scan(tmp_path).files}
    assert paths == {"pkg/keep.py", "secret_gen.py"}


def test_symlinks_are_never_followed(tmp_path):
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "leak.py").write_text("SECRET = 1\n")
    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / "a.py").write_text("x = 1\n")
    try:
        os.symlink(outside, repo / "linked_dir")
        os.symlink(outside / "leak.py", repo / "linked.py")
    except (OSError, NotImplementedError):
        pytest.skip("symlinks unavailable")
    r = scan(repo)
    assert {f.rel_path for f in r.files} == {"a.py"}
    assert {s.reason for s in r.skipped} == {"symlink"}


def test_oversized_file_skipped(tmp_path):
    (tmp_path / "big.py").write_text("x = 1\n" * 1000)
    r = scan(tmp_path, max_file_bytes=1000)
    assert not r.files and r.skipped[0].reason.startswith("too_large")


def test_file_limit(tmp_path):
    for i in range(5):
        (tmp_path / f"f{i}.py").write_text("x = 1\n")
    r = scan(tmp_path, max_files=3)
    assert len(r.files) == 3 and sum(1 for s in r.skipped if s.reason == "file_limit") == 2


def test_extra_ignore_patterns(repo_copy):
    paths = {f.rel_path for f in scan(repo_copy, extra_ignore=["services"]).files}
    assert not any(p.startswith("services/") for p in paths)


def test_content_policy():
    assert check_content_policy(b"abc\x00def") == "binary"
    assert check_content_policy(b"# Code generated by x. DO NOT EDIT.\nx=1") == "generated"
    assert check_content_policy(b"a=1;" * 5000) == "minified"
    assert check_content_policy(b"") == "empty"
    assert check_content_policy(b"def f():\n    return 1\n") is None


def test_language_detection():
    assert detect_language("x.TSX") == "typescript"
    assert detect_language("Makefile") is None
    assert detect_language("a.go") == "go"


def test_unreadable_directory_is_reported(tmp_path):
    d = tmp_path / "locked"
    d.mkdir()
    (d / "a.py").write_text("x=1\n")
    d.chmod(0)
    try:
        if os.access(d, os.R_OK):
            pytest.skip("running as a user that ignores permissions (e.g. root)")
        r = scan(tmp_path)
        assert any(s.reason.startswith("unreadable") for s in r.skipped)
    finally:
        d.chmod(0o755)
