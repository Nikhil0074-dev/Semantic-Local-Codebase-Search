"""Repository discovery: what to index, what to skip, and why. Never follows symlinks, never leaves the root."""
from __future__ import annotations

import fnmatch
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import pathspec

from .config import DEFAULT_EXCLUDE_DIRS, LOCKFILES, SENSITIVE_ALLOW, SENSITIVE_PATTERNS, Settings

LANGUAGE_BY_EXT = {
    ".py": "python", ".pyi": "python",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript",
    ".java": "java", ".go": "go", ".rs": "rust", ".cs": "csharp", ".php": "php",
    ".c": "c", ".h": "c", ".cc": "cpp", ".cpp": "cpp", ".cxx": "cpp", ".hpp": "cpp", ".hh": "cpp",
    ".sql": "sql",
    ".yaml": "config", ".yml": "config", ".toml": "config", ".ini": "config", ".cfg": "config", ".json": "config",
}
# Tier-1: symbol-aware and covered by dedicated tests. Others fall back to line windows if parsing finds nothing.
SYMBOL_AWARE = ("python", "javascript", "typescript", "java", "go", "rust", "csharp", "php", "c", "cpp", "sql")
GENERATED_MARKERS = ("do not edit", "@generated", "code generated", "auto-generated", "autogenerated", "generated by")


@dataclass
class ScannedFile:
    rel_path: str
    abs_path: str
    language: str
    size: int
    mtime_ns: int


@dataclass
class SkippedItem:
    rel_path: str
    reason: str


@dataclass
class ScanResult:
    files: list[ScannedFile] = field(default_factory=list)
    skipped: list[SkippedItem] = field(default_factory=list)
    unsupported_count: int = 0


def detect_language(name: str) -> Optional[str]:
    return LANGUAGE_BY_EXT.get(os.path.splitext(name)[1].lower())


def _matches_any(name: str, patterns) -> bool:
    low = name.lower()
    return any(fnmatch.fnmatch(low, p.lower()) for p in patterns)


def is_sensitive(name: str) -> bool:
    if name.lower() in SENSITIVE_ALLOW:
        return False
    return _matches_any(name, SENSITIVE_PATTERNS)


def _looks_binary(head: bytes) -> bool:
    return b"\x00" in head


def check_content_policy(raw: bytes) -> Optional[str]:
    """Content-based skip reasons evaluated by the indexer for new/changed files only."""
    if _looks_binary(raw[:8192]):
        return "binary"
    head = raw[:2048].lower()
    if any(m.encode() in head for m in GENERATED_MARKERS):
        return "generated"
    if not raw:
        return "empty"
    nlines = raw.count(b"\n") + 1
    if len(raw) / nlines > 400 or any(len(l) > 5000 for l in raw.split(b"\n")):
        return "minified"
    return None


def _load_gitignore(path: str):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            lines = fh.read().splitlines()
        return pathspec.GitIgnoreSpec.from_lines(lines)
    except OSError:
        return None


def scan_repository(root: str | os.PathLike, settings: Settings) -> ScanResult:
    root_p = Path(root).resolve()
    result = ScanResult()
    extra = list(settings.extra_ignore)
    excluded_dirs = {d.lower() for d in DEFAULT_EXCLUDE_DIRS}
    # stack items: (abs_dir, rel_dir, gitignore specs as [(rel_dir_of_spec, spec)])
    stack: list[tuple[str, str, list]] = [(str(root_p), "", [])]
    while stack:
        d, rel, specs = stack.pop()
        try:
            entries = sorted(os.scandir(d), key=lambda e: e.name)
        except OSError as exc:
            result.skipped.append(SkippedItem(rel or ".", f"unreadable: {exc.strerror or 'error'}"))
            continue
        local_specs = specs
        if settings.respect_gitignore:
            gi = os.path.join(d, ".gitignore")
            if os.path.isfile(gi):
                spec = _load_gitignore(gi)
                if spec is not None:
                    local_specs = specs + [(rel, spec)]

        def ignored(rel_path: str, is_dir: bool) -> bool:
            for base, spec in local_specs:
                sub = rel_path[len(base) + 1:] if base else rel_path
                if spec.match_file(sub + ("/" if is_dir else "")):
                    return True
            return False

        subdirs = []
        for e in entries:
            rel_path = f"{rel}/{e.name}" if rel else e.name
            try:
                if e.is_symlink():
                    result.skipped.append(SkippedItem(rel_path, "symlink"))
                    continue
                if e.is_dir(follow_symlinks=False):
                    if e.name.lower() in excluded_dirs or _matches_any(e.name, extra) or _matches_any(rel_path, extra):
                        result.skipped.append(SkippedItem(rel_path + "/", "excluded_dir"))
                    elif ignored(rel_path, True):
                        result.skipped.append(SkippedItem(rel_path + "/", "gitignored"))
                    else:
                        subdirs.append((e.path, rel_path, local_specs))
                    continue
                if not e.is_file(follow_symlinks=False):
                    continue
                lang = detect_language(e.name)
                if is_sensitive(e.name):
                    result.skipped.append(SkippedItem(rel_path, "sensitive"))
                    continue
                if lang is None:
                    result.unsupported_count += 1
                    continue
                if e.name in LOCKFILES or e.name.endswith((".min.js", ".min.css", ".map")):
                    result.skipped.append(SkippedItem(rel_path, "lockfile_or_minified"))
                    continue
                if _matches_any(rel_path, extra) or _matches_any(e.name, extra):
                    result.skipped.append(SkippedItem(rel_path, "user_ignore"))
                    continue
                if ignored(rel_path, False):
                    result.skipped.append(SkippedItem(rel_path, "gitignored"))
                    continue
                st = e.stat(follow_symlinks=False)
                if st.st_size > settings.max_file_bytes:
                    result.skipped.append(SkippedItem(rel_path, f"too_large ({st.st_size} bytes)"))
                    continue
                if len(result.files) >= settings.max_files:
                    result.skipped.append(SkippedItem(rel_path, "file_limit"))
                    continue
                result.files.append(ScannedFile(rel_path, e.path, lang, st.st_size, st.st_mtime_ns))
            except OSError as exc:
                result.skipped.append(SkippedItem(rel_path, f"unreadable: {exc.strerror or 'error'}"))
        stack.extend(reversed(subdirs))
    result.files.sort(key=lambda f: f.rel_path)
    return result
